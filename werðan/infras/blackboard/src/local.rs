/// Isolated 4-slice Local Blackboard for vertex v_i: B^(v_i) = (B_PM, B_SH, B_CT, B_PR).
#[derive(::core::clone::Clone, ::core::fmt::Debug, ::core::default::Default)]
pub struct LocalBlackboard {
    pub problem_model: self::ProblemModelSlice,
    pub strategies: self::StrategyHypothesesSlice,
    pub characterization_tests: self::CharacterizationTestsSlice,
    pub patch_records: self::PatchRecordsSlice,
}

impl self::LocalBlackboard {
    /// Initialize with hydrated Problem Model slice.
    pub fn new(problem_model: self::ProblemModelSlice) -> Self {
        Self {
            problem_model,
            strategies: self::StrategyHypothesesSlice::default(),
            characterization_tests: self::CharacterizationTestsSlice::default(),
            patch_records: self::PatchRecordsSlice::default(),
        }
    }

    /// Obtain read-isolated view for adversarial test generator (A_test).
    /// By construction, A_test cannot access candidate code drafts.
    pub fn test_generator_view(&self) -> self::TestGeneratorView<'_> {
        self::TestGeneratorView {
            problem_model: &self.problem_model,
        }
    }

    /// Obtain view for code generation agent (A_gen).
    pub fn code_generator_view(&self) -> self::CodeGeneratorView<'_> {
        self::CodeGeneratorView {
            problem_model: &self.problem_model,
            strategies: &self.strategies,
        }
    }

    /// Obtain view for surgical patch repair agent (A_patch).
    pub fn patch_repair_view(&self) -> self::PatchRepairView<'_> {
        self::PatchRepairView {
            problem_model: &self.problem_model,
            patch_records: &self.patch_records,
        }
    }
}

/// Compile-time read-isolated view for A_test.
/// Note: Contains absolutely NO candidate code field, guaranteeing test-weakening prevention by type construction.
pub struct TestGeneratorView<'a> {
    pub problem_model: &'a self::ProblemModelSlice,
}

/// View for A_gen.
pub struct CodeGeneratorView<'a> {
    pub problem_model: &'a self::ProblemModelSlice,
    pub strategies: &'a self::StrategyHypothesesSlice,
}

/// View for A_patch.
pub struct PatchRepairView<'a> {
    pub problem_model: &'a self::ProblemModelSlice,
    pub patch_records: &'a self::PatchRecordsSlice,
}
