//! Per-Module 4-Slice Local Blackboard B^(v_i) and compile-time read-isolation traits.
//! Formalized per §2 Definition 2 and §4.2 in `METHODOLOGY.md`.

use self::super::global::InterfaceSpec;
use self::super::global::RuleCard;

/// Classification of diagnostic fault causes in Stage 3b evaluation.
#[derive(
    ::core::clone::Clone,
    ::core::marker::Copy,
    ::core::fmt::Debug,
    ::core::cmp::PartialEq,
    ::core::cmp::Eq,
    ::serde::Serialize,
    ::serde::Deserialize
)]
pub enum FaultCause {
    /// Intrinsic to module logic (resolved locally via Tier-A MCTS).
    Intrinsic,
    /// Extrinsic parent contract conflict (triggers Tier-B micro-regression).
    ExtrinsicContract,
    /// Extrinsic dependency cycle discovered (triggers Tier-C macro-regression).
    ExtrinsicCycle,
}

/// Refactoring hypothesis h_k generated by A_str.
#[derive(
    ::bon::Builder,
    ::core::clone::Clone,
    ::core::fmt::Debug,
    ::core::cmp::PartialEq,
    ::serde::Serialize,
    ::serde::Deserialize
)]
pub struct StrategyHypothesis {
    /// Unique hypothesis identifier.
    #[builder(into)]
    pub id: ::std::string::String,
    /// Architectural approach description (e.g., state pattern vs. functional port).
    #[builder(into)]
    pub description: ::std::string::String,
    /// Prior utility estimate from Laya or heuristics: P_prior(u).
    pub prior_score: ::core::primitive::f64,
}

/// Black-box I/O test snapshot or property-based test fixture.
#[derive(
    ::bon::Builder,
    ::core::clone::Clone,
    ::core::fmt::Debug,
    ::core::cmp::PartialEq,
    ::core::cmp::Eq,
    ::serde::Serialize,
    ::serde::Deserialize
)]
pub struct CharacterizationTestFixture {
    /// Test identifier.
    #[builder(into)]
    pub test_id: ::std::string::String,
    /// Test source code or property assertion.
    #[builder(into)]
    pub test_code: ::std::string::String,
    /// Whether this fixture represents a falsifying counterexample.
    pub is_counterexample: ::core::primitive::bool,
}

/// Distilled fault localization and root-cause trace indexing failed rollouts.
#[derive(
    ::bon::Builder,
    ::core::clone::Clone,
    ::core::fmt::Debug,
    ::core::cmp::PartialEq,
    ::core::cmp::Eq,
    ::serde::Serialize,
    ::serde::Deserialize
)]
pub struct FaultRecord {
    /// Search tree node or rollout index.
    pub rollout_index: ::core::primitive::usize,
    /// Localized fault line or AST node.
    #[builder(into)]
    pub localized_location: ::std::string::String,
    /// Distilled compiler or test diagnostic summary.
    #[builder(into)]
    pub diagnostic_summary: ::std::string::String,
    /// Classified fault root cause.
    pub cause: self::FaultCause,
}

/// Slice 1: Problem Model (B_PM^(v_i))
/// Hydrated deterministically from G upon module activation.
#[derive(
    ::bon::Builder,
    ::core::clone::Clone,
    ::core::fmt::Debug,
    ::core::cmp::PartialEq,
    ::core::cmp::Eq,
    ::core::default::Default,
    ::serde::Serialize,
    ::serde::Deserialize
)]
pub struct ProblemModelSlice {
    /// Active module vertex identifier.
    #[builder(into)]
    pub vertex_id: ::std::string::String,
    /// Legacy source code AST slices.
    #[serde(default)]
    #[builder(default)]
    pub legacy_ast_slices: ::std::vec::Vec<::std::string::String>,
    /// Verified Given/When/Then business rule cards.
    #[serde(default)]
    #[builder(default)]
    pub verified_rules: ::std::vec::Vec<self::RuleCard>,
    /// Upstream parent interface contracts.
    #[serde(default)]
    #[builder(default)]
    pub parent_contracts: ::std::vec::Vec<self::InterfaceSpec>,
    /// Downstream export obligations expected from this module.
    #[serde(default)]
    #[builder(default)]
    pub export_obligations: ::std::vec::Vec<::std::string::String>,
}

